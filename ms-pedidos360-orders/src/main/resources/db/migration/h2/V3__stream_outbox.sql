ALTER TABLE P360_ORDERS ADD STREAM_VERSION BIGINT DEFAULT 0 NOT NULL;
CREATE TABLE P360_STREAM_OUTBOX (
 ID VARCHAR(36) PRIMARY KEY,
 ORDER_ID BIGINT NOT NULL,
 EVENT_VERSION BIGINT NOT NULL,
 PAYLOAD CLOB NOT NULL,
 CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 NEXT_ATTEMPT TIMESTAMP WITH TIME ZONE NOT NULL,
 ATTEMPTS INTEGER NOT NULL,
 PUBLISHED_AT TIMESTAMP WITH TIME ZONE,
 LAST_ERROR VARCHAR(100),
 CONSTRAINT UQ_STREAM_ORDER_VERSION UNIQUE (ORDER_ID, EVENT_VERSION)
);
CREATE INDEX IDX_STREAM_READY ON P360_STREAM_OUTBOX(PUBLISHED_AT,NEXT_ATTEMPT);

