CREATE TABLE P360_TIMELINE (
 ID VARCHAR2(36) PRIMARY KEY, LOCK_VERSION NUMBER(19), ORDER_ID NUMBER(19) NOT NULL,
 EVENT_VERSION NUMBER(19) NOT NULL, STORE_ID NUMBER(19) NOT NULL, ACTOR_ID VARCHAR2(250) NOT NULL,
 ACTION VARCHAR2(40) NOT NULL, TYPE VARCHAR2(40) NOT NULL,
 PREVIOUS_STATUS VARCHAR2(30), STATUS VARCHAR2(30) NOT NULL,
 OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL, CORRELATION_ID VARCHAR2(128) NOT NULL,
 SOURCE VARCHAR2(80) NOT NULL, PAYLOAD CLOB NOT NULL, NEXT_ATTEMPT TIMESTAMP WITH TIME ZONE NOT NULL,
 ATTEMPTS INTEGER NOT NULL, PUBLISHED_AT TIMESTAMP WITH TIME ZONE,
 PROJECTED_AT TIMESTAMP WITH TIME ZONE, LAST_ERROR VARCHAR2(100)
);
CREATE INDEX IDX_TIMELINE_ORDER ON P360_TIMELINE(ORDER_ID,OCCURRED_AT);
CREATE INDEX IDX_TIMELINE_ACTOR ON P360_TIMELINE(ACTOR_ID,OCCURRED_AT);
CREATE INDEX IDX_TIMELINE_PENDING ON P360_TIMELINE(PUBLISHED_AT,NEXT_ATTEMPT);

