CREATE TABLE P360_TIMELINE (
 ID VARCHAR(36) PRIMARY KEY, LOCK_VERSION BIGINT, ORDER_ID BIGINT NOT NULL,
 EVENT_VERSION BIGINT NOT NULL, STORE_ID BIGINT NOT NULL, ACTOR_ID VARCHAR(250) NOT NULL,
 ACTION VARCHAR(40) NOT NULL, TYPE VARCHAR(40) NOT NULL,
 PREVIOUS_STATUS VARCHAR(30), STATUS VARCHAR(30) NOT NULL,
 OCCURRED_AT TIMESTAMP WITH TIME ZONE NOT NULL, CORRELATION_ID VARCHAR(128) NOT NULL,
 SOURCE VARCHAR(80) NOT NULL, PAYLOAD CLOB NOT NULL, NEXT_ATTEMPT TIMESTAMP WITH TIME ZONE NOT NULL,
 ATTEMPTS INTEGER NOT NULL, PUBLISHED_AT TIMESTAMP WITH TIME ZONE,
 PROJECTED_AT TIMESTAMP WITH TIME ZONE, LAST_ERROR VARCHAR(100)
);
CREATE INDEX IDX_TIMELINE_ORDER ON P360_TIMELINE(ORDER_ID,OCCURRED_AT);
CREATE INDEX IDX_TIMELINE_ACTOR ON P360_TIMELINE(ACTOR_ID,OCCURRED_AT);
CREATE INDEX IDX_TIMELINE_PENDING ON P360_TIMELINE(PUBLISHED_AT,NEXT_ATTEMPT);

