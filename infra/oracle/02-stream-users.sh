#!/usr/bin/env bash
# Safe for existing volumes: create missing users; never replace passwords or data.
set -euo pipefail
for var in REPORT_DB_PASSWORD AUDIT_DB_PASSWORD; do
  [[ "${!var}" =~ ^[a-f0-9]{32,64}$ ]] || { echo "Invalid generated streaming DB password" >&2; exit 1; }
done
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;
DECLARE
 n NUMBER;
BEGIN
 SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME='P360_REPORT';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE USER P360_REPORT IDENTIFIED BY "${REPORT_DB_PASSWORD}"'; END IF;
 SELECT COUNT(*) INTO n FROM DBA_USERS WHERE USERNAME='P360_AUDIT';
 IF n=0 THEN EXECUTE IMMEDIATE 'CREATE USER P360_AUDIT IDENTIFIED BY "${AUDIT_DB_PASSWORD}"'; END IF;
END;
/
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO P360_REPORT, P360_AUDIT;
ALTER USER P360_REPORT QUOTA UNLIMITED ON USERS;
ALTER USER P360_AUDIT QUOTA UNLIMITED ON USERS;
SQL

