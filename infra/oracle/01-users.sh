#!/bin/bash
set -euo pipefail
for var in ORDERS_DB_PASSWORD CATALOG_DB_PASSWORD NOTIFY_DB_PASSWORD; do
 [[ "${!var}" =~ ^[a-f0-9]{32,64}$ ]] || { echo "Invalid generated DB password"; exit 1; }
done
sqlplus -s / as sysdba <<SQL
WHENEVER SQLERROR EXIT SQL.SQLCODE
ALTER SESSION SET CONTAINER=FREEPDB1;
CREATE USER P360_ORDERS IDENTIFIED BY "${ORDERS_DB_PASSWORD}";
CREATE USER P360_CATALOG IDENTIFIED BY "${CATALOG_DB_PASSWORD}";
CREATE USER P360_NOTIFY IDENTIFIED BY "${NOTIFY_DB_PASSWORD}";
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO P360_ORDERS, P360_CATALOG, P360_NOTIFY;
ALTER USER P360_ORDERS QUOTA UNLIMITED ON USERS;
ALTER USER P360_CATALOG QUOTA UNLIMITED ON USERS;
ALTER USER P360_NOTIFY QUOTA UNLIMITED ON USERS;
SQL
