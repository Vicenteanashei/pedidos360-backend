CREATE TABLE P360_REPORT_ORDERS (
 ID BIGINT PRIMARY KEY, LOCK_VERSION BIGINT, EVENT_VERSION BIGINT NOT NULL,
 STORE_ID BIGINT NOT NULL, STATUS VARCHAR(30) NOT NULL, DELETED BOOLEAN NOT NULL,
 TOTAL DECIMAL(12,2) NOT NULL, CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 DELIVERED_AT TIMESTAMP WITH TIME ZONE, EVENT_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 SALES_DAY VARCHAR(10), SALES_HOUR VARCHAR(32), LEAD_TIME_MS BIGINT
);
CREATE INDEX IDX_REPORT_DELIVERED ON P360_REPORT_ORDERS(STATUS,DELETED,DELIVERED_AT);
CREATE TABLE P360_REPORT_LINES (
 ORDER_ID BIGINT NOT NULL REFERENCES P360_REPORT_ORDERS(ID),
 PRODUCT_ID BIGINT NOT NULL, QUANTITY INTEGER NOT NULL
);
CREATE INDEX IDX_REPORT_LINES_ORDER ON P360_REPORT_LINES(ORDER_ID);

