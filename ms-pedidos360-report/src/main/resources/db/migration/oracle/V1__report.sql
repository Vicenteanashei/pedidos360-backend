CREATE TABLE P360_REPORT_ORDERS (
 ID NUMBER(19) PRIMARY KEY, LOCK_VERSION NUMBER(19), EVENT_VERSION NUMBER(19) NOT NULL,
 STORE_ID NUMBER(19) NOT NULL, STATUS VARCHAR2(30) NOT NULL, DELETED BOOLEAN NOT NULL,
 TOTAL NUMBER(12,2) NOT NULL, CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 DELIVERED_AT TIMESTAMP WITH TIME ZONE, EVENT_AT TIMESTAMP WITH TIME ZONE NOT NULL,
 SALES_DAY VARCHAR2(10), SALES_HOUR VARCHAR2(32), LEAD_TIME_MS NUMBER(19)
);
CREATE INDEX IDX_REPORT_DELIVERED ON P360_REPORT_ORDERS(STATUS,DELETED,DELIVERED_AT);
CREATE TABLE P360_REPORT_LINES (
 ORDER_ID NUMBER(19) NOT NULL REFERENCES P360_REPORT_ORDERS(ID),
 PRODUCT_ID NUMBER(19) NOT NULL, QUANTITY INTEGER NOT NULL
);
CREATE INDEX IDX_REPORT_LINES_ORDER ON P360_REPORT_LINES(ORDER_ID);

